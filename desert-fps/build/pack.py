"""Packs the Luau sources in ../game into files Studio can load.

    python pack.py

The folder tree under game/ mirrors the place: game/<Service>/<Folder>/<Name>.luau.
A file ending in .server.luau is a Script, .client.luau a LocalScript, anything else a ModuleScript.
Data the game reads is packed as modules that return the decoded JSON:
    plan/out/plan.json, routes.json           ServerStorage/DesertFps/Plan/PlanData, RouteData
    assets/out/<piece>/<piece>.break.json     ServerStorage/DesertFps/Assets/BreakData (keyed by piece)
    assets/out/<piece>/<piece>.parts.json     ServerStorage/DesertFps/Assets/PartsData (keyed by piece)
    assets/out/buildings/<name>.json          ServerStorage/DesertFps/Buildings/BuildingData (keyed by building)

Writes:
    01_install_modules.luau   paste into the Studio command bar to (re)install every script
    out/<Service>.rbxmx       the same scripts as model files, one per place to import into
"""
import json
import os
import re
from xml.sax.saxutils import escape

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GAME = os.path.join(ROOT, "game")
PLAN_OUT = os.path.join(ROOT, "plan", "out")
# plan/out JSON files packed as data modules under ServerStorage/DesertFps/Plan.
PLAN_DATA = {"PlanData": "plan.json", "RouteData": "routes.json"}
ASSETS_OUT = os.path.join(ROOT, "assets", "out")
# assets/out/<piece>/<piece>.<kind>.json files packed as data modules under ServerStorage/DesertFps/Assets.
ASSET_DATA = {"BreakData": "break", "PartsData": "parts"}
BUILDINGS_OUT = os.path.join(ASSETS_OUT, "buildings")
OUT = os.path.join(HERE, "out")
# Services whose scripts go in a child of the service: how many path parts name the place to import into.
CONTAINERS = {"StarterPlayer": 2}


def long_string(text):
    """A Luau long-bracket literal whose closing bracket does not appear in the text."""
    level = 1
    while "]" + "=" * level + "]" in text:
        level += 1
    eq = "=" * level
    return f"[{eq}[\n{text}]{eq}]"


def data_module(data, source):
    body = json.dumps(data, separators=(",", ":"))
    return (
        "--!strict\n"
        f"-- Generated by build/pack.py from {source}. Do not edit; rebuild the source and re-run pack.py.\n"
        'local HttpService = game:GetService("HttpService")\n\n'
        f"return HttpService:JSONDecode({long_string(body)}) :: any\n"
    )


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def piece_data(kind):
    """Every piece's <piece>.<kind>.json (break data, or a weapon's parts data), keyed by piece name."""
    pieces = {}
    for piece in sorted(os.listdir(ASSETS_OUT)):
        path = os.path.join(ASSETS_OUT, piece, f"{piece}.{kind}.json")
        if os.path.isfile(path):
            pieces[piece] = load(path)
    return pieces


def collect():
    """Every script as (path parts from the service down, class name, source)."""
    scripts = []
    for folder, _, files in os.walk(GAME):
        for name in sorted(files):
            if not name.endswith(".luau"):
                continue
            stem = name[: -len(".luau")]
            cls = "ModuleScript"
            if stem.endswith(".server"):
                stem, cls = stem[: -len(".server")], "Script"
            elif stem.endswith(".client"):
                stem, cls = stem[: -len(".client")], "LocalScript"
            rel = os.path.relpath(folder, GAME).replace("\\", "/").split("/")
            with open(os.path.join(folder, name), encoding="utf-8") as f:
                scripts.append((rel + [stem], cls, f.read()))
    for module, file_name in PLAN_DATA.items():
        source = data_module(load(os.path.join(PLAN_OUT, file_name)), "plan/out/" + file_name)
        scripts.append((["ServerStorage", "DesertFps", "Plan", module], "ModuleScript", source))
    for module, kind in ASSET_DATA.items():
        source = data_module(piece_data(kind), f"assets/out/<piece>/<piece>.{kind}.json")
        scripts.append((["ServerStorage", "DesertFps", "Assets", module], "ModuleScript", source))
    buildings = {name[:-5]: load(os.path.join(BUILDINGS_OUT, name)) for name in sorted(os.listdir(BUILDINGS_OUT))
                 if name.endswith(".json")}
    scripts.append((["ServerStorage", "DesertFps", "Buildings", "BuildingData"], "ModuleScript",
                    data_module(buildings, "assets/out/buildings/<name>.json")))
    return sorted(scripts)


def write_install(scripts):
    lines = [
        "-- Generated by build/pack.py. Do not edit: change the sources under game/ and re-run pack.py.",
        "-- Run in Studio in edit mode (command bar or MCP) to install or update every project script.",
        "local SCRIPTS = {",
    ]
    for path, cls, source in scripts:
        quoted = ", ".join(f'"{p}"' for p in path)
        lines.append(f'\t{{ path = {{ {quoted} }}, class = "{cls}", source = {long_string(source)} }},')
    lines += [
        "}",
        "",
        "for _, entry in SCRIPTS do",
        "\tlocal parent: Instance = game:GetService(entry.path[1])",
        "\tfor i = 2, #entry.path - 1 do",
        "\t\tlocal folder = parent:FindFirstChild(entry.path[i])",
        "\t\tif not folder then",
        '\t\t\tfolder = Instance.new("Folder")',
        "\t\t\tfolder.Name = entry.path[i]",
        "\t\t\tfolder.Parent = parent",
        "\t\tend",
        "\t\tparent = folder",
        "\tend",
        "\tlocal name = entry.path[#entry.path]",
        "\tlocal old = parent:FindFirstChild(name)",
        "\tif old then",
        "\t\told:Destroy()",
        "\tend",
        "\tlocal scriptInstance = Instance.new(entry.class)",
        "\tscriptInstance.Name = name",
        "\tscriptInstance.Source = entry.source",
        "\tscriptInstance.Parent = parent",
        "end",
        "",
        'game:GetService("ChangeHistoryService"):SetWaypoint("Install Desert FPS scripts")',
        "return #SCRIPTS",
        "",
    ]
    with open(os.path.join(HERE, "01_install_modules.luau"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def write_models(scripts):
    """One .rbxmx per place to import into (ServerStorage, StarterPlayer.StarterPlayerScripts, ...),
    holding the top-level folders that go there."""
    os.makedirs(OUT, exist_ok=True)
    trees = {}
    for path, cls, source in scripts:
        depth = CONTAINERS.get(path[0], 1)
        node = trees.setdefault(".".join(path[:depth]), {})
        for part in path[depth:-1]:
            node = node.setdefault(part, {})
        node[path[-1]] = (cls, source)

    def item(name, value, depth):
        pad = "  " * depth
        if isinstance(value, tuple):
            cls, source = value
            cdata = source.replace("]]>", "]]]]><![CDATA[>")
            return (
                f'{pad}<Item class="{cls}">\n{pad}  <Properties>\n'
                f'{pad}    <string name="Name">{escape(name)}</string>\n'
                f'{pad}    <ProtectedString name="Source"><![CDATA[{cdata}]]></ProtectedString>\n'
                f"{pad}  </Properties>\n{pad}</Item>\n"
            )
        children = "".join(item(k, v, depth + 1) for k, v in sorted(value.items()))
        return (
            f'{pad}<Item class="Folder">\n{pad}  <Properties>\n'
            f'{pad}    <string name="Name">{escape(name)}</string>\n'
            f"{pad}  </Properties>\n{children}{pad}</Item>\n"
        )

    for service, tree in trees.items():
        body = "".join(item(k, v, 1) for k, v in sorted(tree.items()))
        with open(os.path.join(OUT, service + ".rbxmx"), "w", encoding="utf-8", newline="\n") as f:
            f.write(f'<roblox version="4">\n{body}</roblox>\n')


def main():
    scripts = collect()
    for path, _, source in scripts:
        assert not re.search(r"\r", source), f"{'/'.join(path)}: use LF line endings"
    write_install(scripts)
    write_models(scripts)
    for path, cls, source in scripts:
        print(f"{cls:13} {'/'.join(path)}  ({len(source.splitlines())} lines)")


if __name__ == "__main__":
    main()
